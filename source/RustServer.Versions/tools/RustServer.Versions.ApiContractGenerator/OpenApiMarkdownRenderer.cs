using System.Text;
using System.Text.Json.Nodes;

namespace RustServer.Versions.ApiContractGenerator;

public static class OpenApiMarkdownRenderer
{
    public static string Render(JsonNode openApiDocument)
    {
        ArgumentNullException.ThrowIfNull(openApiDocument);

        var document = openApiDocument.AsObject();
        var info = document["info"]?.AsObject()
            ?? throw new InvalidOperationException("The OpenAPI document does not contain info.");
        var lines = new List<string>
        {
            $"# {info["title"]?.GetValue<string>() ?? "API"} contract",
            string.Empty,
            "> Generated from [`openapi.json`](../openapi.json). Do not edit this file manually.",
            string.Empty,
            "## Overview",
            string.Empty,
            $"- OpenAPI version: `{document["openapi"]?.GetValue<string>() ?? "unknown"}`",
            $"- API version: `{info["version"]?.GetValue<string>() ?? "unknown"}`",
            "- Runtime document: `GET /openapi.json`",
            string.Empty
        };

        var description = info["description"]?.GetValue<string>();
        if (!string.IsNullOrWhiteSpace(description))
        {
            lines.Add(description);
            lines.Add(string.Empty);
        }

        lines.Add("## Endpoints");
        lines.Add(string.Empty);

        foreach (var (path, pathItem) in GetProperties(document["paths"]))
        {
            foreach (var (method, operation) in GetProperties(pathItem))
            {
                if (!IsHttpMethod(method))
                {
                    continue;
                }

                lines.Add($"### {method.ToUpperInvariant()} `{path}`");
                lines.Add(string.Empty);

                var summary = operation["summary"]?.GetValue<string>();
                if (!string.IsNullOrWhiteSpace(summary))
                {
                    lines.Add(summary);
                    lines.Add(string.Empty);
                }

                lines.Add("| Status | Description | Response | Content type |");
                lines.Add("| --- | --- | --- | --- |");

                foreach (var (status, response) in GetProperties(operation["responses"]))
                {
                    var content = response["content"]?.AsObject();
                    var mediaTypes = content is null
                        ? Array.Empty<string>()
                        : content.Select(entry => entry.Key).OrderBy(value => value, StringComparer.Ordinal).ToArray();
                    var schema = content?["application/json"]?["schema"]
                        ?? content?.FirstOrDefault().Value?["schema"];

                    lines.Add($"| `{status}` | {GetText(response["description"])} | {GetSchemaName(schema)} | {string.Join(", ", mediaTypes.Select(value => $"`{value}`"))} |");
                }

                lines.Add(string.Empty);
            }
        }

        lines.Add("## Models");
        lines.Add(string.Empty);

        foreach (var (name, schema) in GetProperties(document["components"]?["schemas"])
                     .OrderBy(entry => entry.Name, StringComparer.Ordinal))
        {
            lines.Add($"### `{name}`");
            lines.Add(string.Empty);

            var schemaDescription = schema["description"]?.GetValue<string>();
            if (!string.IsNullOrWhiteSpace(schemaDescription))
            {
                lines.Add(schemaDescription);
                lines.Add(string.Empty);
            }

            lines.Add("| Field | Type | Required | Nullable | Description |");
            lines.Add("| --- | --- | --- | --- | --- |");

            var requiredProperties = GetStringValues(schema["required"]);
            foreach (var (propertyName, property) in GetProperties(schema["properties"])
                         .OrderBy(entry => entry.Name, StringComparer.Ordinal))
            {
                var isRequired = requiredProperties.Contains(propertyName, StringComparer.Ordinal);
                var isNullable = property["nullable"]?.GetValue<bool>() == true;
                lines.Add($"| `{propertyName}` | {GetSchemaName(property)} | {(isRequired ? "Yes" : "No")} | {(isNullable ? "Yes" : "No")} | {GetText(property["description"])} |");
            }

            lines.Add(string.Empty);
        }

        return string.Join(Environment.NewLine, lines).TrimEnd() + Environment.NewLine;
    }

    private static IEnumerable<(string Name, JsonObject Value)> GetProperties(JsonNode? node) =>
        node is JsonObject objectNode
            ? objectNode
                .Where(entry => entry.Value is JsonObject)
                .Select(entry => (entry.Key, entry.Value!.AsObject()))
            : Enumerable.Empty<(string Name, JsonObject Value)>();

    private static IEnumerable<string> GetStringValues(JsonNode? node) =>
        node is JsonArray array
            ? array.Where(item => item is not null).Select(item => item!.GetValue<string>())
            : Enumerable.Empty<string>();

    private static bool IsHttpMethod(string value) => value is "get" or "put" or "post" or "delete" or "options" or "head" or "patch" or "trace";

    private static string GetSchemaName(JsonNode? schema)
    {
        if (schema is not JsonObject schemaObject)
        {
            return "—";
        }

        var reference = schemaObject["$ref"]?.GetValue<string>();
        if (!string.IsNullOrWhiteSpace(reference))
        {
            return $"`{reference.Split('/').Last()}`";
        }

        var allOfReference = schemaObject["allOf"]?
            .AsArray()
            .Select(item => item?["$ref"]?.GetValue<string>())
            .FirstOrDefault(value => !string.IsNullOrWhiteSpace(value));
        if (!string.IsNullOrWhiteSpace(allOfReference))
        {
            return $"`{allOfReference.Split('/').Last()}`";
        }

        var type = schemaObject["type"]?.GetValue<string>() ?? "object";
        var format = schemaObject["format"]?.GetValue<string>();
        return string.IsNullOrWhiteSpace(format) ? $"`{type}`" : $"`{type} ({format})`";
    }

    private static string GetText(JsonNode? value) =>
        value?.GetValue<string>()?.Replace("|", "\\|", StringComparison.Ordinal) ?? "—";
}
